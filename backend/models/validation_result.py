"""
Defines the Valudation Result model used by all validators.

Each validator returns a ValidationResult object. 
The ValidationEngine aggregates these results before passing them to the Recommendation Engine.
"""

from typing import List
from enum import Enum
from pydantic import BaseModel, Field, ConfigDict
from models.recommendation import Recommendation

class ValidationResult(BaseModel):
    #Represents the result of a validation returned by a validator.

    model_config = ConfigDict(
        validate_assignment=True,
        use_enum_values=True,
        extra="forbid",
        frozen=False,
        json_schema_extra = {
            "example": {
                "validator": "SecurityValidator",
                "status": "Warning",
                "issues_found": 2,
                "execution_time": 0.45,
                "recommendations": [
                    {
                        "id": "6f31d97e-8c3b-4f1a-9f2e-1c2b3d4e5f6a",
                        "category":"Security",
                        "severity":"High",
                        "title":"Hardcoded Password",
                        "message":"Replace hardcoded password with a Terraform variable.",
                        "line_number": 12,
                        "resource": "aws_db_instance.database",
                        "original_value": "password= \"admin123\"",
                        "suggested_value": "password = var.db_password",
                        "auto_fixable": True,
                        "validator": "SecurityValidator"
                    }
                ]
            }
        }
    )

    validator: str = Field(
        ...,
        description= "Name of the validator."
    )

    status: str = Field(
        ...,
        description= "Validation status (Success, Warning, Failed)."
    )

    issues_found: int = Field(
        default=0,
        ge=0,
        description= "Total number of issues found."
    )

    execution_time_ms: float = Field(
        default=0.0,
        ge=0,
        description= "Execution time in milliseconds."
    )

    recommendations: List[Recommendation] = Field(
        default_factory=list,
        description= "List of recommendations generated by the validator."
    )